"""Converts the Lucide SVGs in tools/lucide into WPF StreamGeometry resources (Icons.xaml).

Lucide icons are 24x24 stroke icons. Supports the element types they use: path, polygon, line, rect (with rx), circle.
Run:  python tools/gen-icons.py
"""
import re, pathlib

root = pathlib.Path(__file__).parent
names = {
    "skip-back": "SkipBack", "play": "Play", "pause": "Pause", "skip-forward": "SkipForward",
    "volume-2": "Volume", "shuffle": "Shuffle", "repeat": "Repeat", "heart": "Heart",
    "repeat-1": "Repeat1", "list-music": "ListMusic", "monitor-speaker": "MonitorSpeaker", "chevron-left": "ChevronLeft",
    "settings": "Settings", "grip-vertical": "Grip", "x": "X", "rotate-ccw": "Reset",
    "check": "Check", "monitor": "Monitor", "smartphone": "Smartphone", "speaker": "Speaker", "tv": "Tv",
}

def attrs(tag):
    return dict(re.findall(r'([\w-]+)="([^"]*)"', tag))

def f(v):
    v = float(v)
    return str(int(v)) if v == int(v) else f"{v:g}"

def convert(svg):
    parts = []
    for tag in re.findall(r"<(?:path|polygon|line|rect|circle)\b[^>]*/>", svg):
        a = attrs(tag)
        if tag.startswith("<path"):
            parts.append(a["d"])
        elif tag.startswith("<polygon"):
            pts = a["points"].split()
            nums = list(map(float, pts))
            xy = [(nums[i], nums[i + 1]) for i in range(0, len(nums), 2)]
            parts.append("M" + " L".join(f"{f(x)} {f(y)}" for x, y in xy) + " Z")
        elif tag.startswith("<line"):
            parts.append(f"M{f(a['x1'])} {f(a['y1'])} L{f(a['x2'])} {f(a['y2'])}")
        elif tag.startswith("<rect"):
            x, y, w, h = (float(a[k]) for k in ("x", "y", "width", "height"))
            r = float(a.get("rx", 0))
            parts.append(
                f"M{f(x + r)} {f(y)} H{f(x + w - r)} A{f(r)} {f(r)} 0 0 1 {f(x + w)} {f(y + r)} "
                f"V{f(y + h - r)} A{f(r)} {f(r)} 0 0 1 {f(x + w - r)} {f(y + h)} H{f(x + r)} "
                f"A{f(r)} {f(r)} 0 0 1 {f(x)} {f(y + h - r)} V{f(y + r)} A{f(r)} {f(r)} 0 0 1 {f(x + r)} {f(y)} Z")
        elif tag.startswith("<circle"):
            cx, cy, r = (float(a[k]) for k in ("cx", "cy", "r"))
            parts.append(f"M{f(cx - r)} {f(cy)} A{f(r)} {f(r)} 0 1 0 {f(cx + r)} {f(cy)} A{f(r)} {f(r)} 0 1 0 {f(cx - r)} {f(cy)} Z")
    # A path element starts absolute even with a lowercase "m"; once joined into one string it would turn relative.
    # Implicit pairs after "m x y" are relative line-tos, so keep them relative with an explicit "l".
    fixed = []
    for x in parts:
        m = re.match(r"^m\s*(-?[\d.]+)[\s,]+(-?[\d.]+)(.*)$", x, re.S)
        if m:
            rest = m.group(3).strip()
            x = f"M{m.group(1)} {m.group(2)}" + ((" l" + rest) if rest and (rest[0].isdigit() or rest[0] in "-.") else (" " + rest if rest else ""))
        fixed.append(x)
    parts = fixed
    return " ".join(parts)

out = ['<!-- Generated by tools/gen-icons.py from Lucide (ISC license, see THIRD-PARTY-LICENSES.txt). Do not edit by hand. -->',
       '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
       '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">']
for file, key in names.items():
    d = convert((root / "lucide" / f"{file}.svg").read_text(encoding="utf-8"))
    out.append(f'    <StreamGeometry x:Key="Icon.{key}">{d}</StreamGeometry>')
out.append("</ResourceDictionary>")
(root.parent / "Icons.xaml").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote Icons.xaml with", len(names), "icons")

lic = (root / "lucide" / "LICENSE").read_text(encoding="utf-8")
(root.parent / "THIRD-PARTY-LICENSES.txt").write_text("Lucide icons (https://lucide.dev), used in Icons.xaml\n\n" + lic, encoding="utf-8")
